`timescale 1ns/1ps
// Candidate consumer boundary: the frozen lifecycle owns all state and timing.
// Every port is passed directly; m_ready and e_ready are independent inputs.
// A consumer completes a window only after accepting samples 0..1023 and m_last.
// STOP drains started windows: continue accepting m/e records and supply PCM
// through the current 250-group packet. An incomplete window is not padded.
// A fault can coexist with verified data draining; m_last alone does not make
// an algorithm result eligible. Recovery requires synchronous whole-slice
// reset and clearing the consumer's uncommitted window state.
// The caller allocates fresh session IDs and owns boot/session identity.
