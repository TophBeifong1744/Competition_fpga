`timescale 1ns/1ps
// B-owned buffer reservation adapter, not a new A source-admission event.
module pcm4_doa_native_entry (

    input logic clk, cold_rst_n,
    input logic [724:0] gate_identity,
    input logic gate_evidence_valid, gate_qualified,
    input logic [63:0] gate_policy_id,
    input logic s_valid, output logic s_ready,
    input logic [63:0] s_token, s_generation,
    input logic [164:0] s_context, input logic [431:0] s_frame_first,
    input logic s_domain, input logic [1:0] s_channel, input logic [9:0] s_bin,
    input logic signed [24:0] s_real, s_imag,
    input logic s_numeric_valid, s_ov_real, s_ov_imag, s_qualified,
    input logic s_terminal_valid, output logic s_terminal_ready,
    input logic [6625:0] s_terminal_data,
    input logic s_abort_valid, output logic s_abort_ready,
    input logic [724:0] s_abort_identity, input logic [179:0] s_abort_data,
    input logic cancel_now, stop_now, input logic [7:0] cancel_causes,
    input logic [724:0] cancel_identity,
    output logic frontend_cancel_request,
    output logic [724:0] active_identity,
    // Exact official AXIS contract: IFFT25, config inverse, natural1024, /2 each stage.
    output logic [23:0] ip_config_data, output logic ip_config_valid,
    input logic ip_config_ready,
    output logic [63:0] ip_input_data, output logic ip_input_valid, ip_input_last,
    input logic ip_input_ready,
    input logic [63:0] ip_output_data, input logic [9:0] ip_output_index,
    input logic ip_output_valid, ip_output_last, output logic ip_output_ready,
    input logic [7:0] ip_status_data, input logic ip_status_valid,
    output logic ip_status_ready,
    input logic ip_event_unexpected_last, ip_event_missing_last, ip_event_overflow,
    output logic report_valid, input logic report_ready,
    output logic signed [17:0] angle_q8,
    output logic angle_numerical_valid, output logic angle_delivery_eligible,
    output logic report_gate_evidence_valid, report_gate_qualified,
    output logic [63:0] report_gate_policy_id,
    output logic [6625:0] frontend_terminal_record,
    output logic frontend_abort_seen,
    output logic [724:0] frontend_abort_identity_record,
    output logic [179:0] frontend_abort_record,
    output logic [23:0] pair_state,
    output logic [83:0] backend_stage_state,
    output logic [5:0] pair_hardware_started, pair_physically_retired, pair_valid,
    output logic [191:0] pair_tau_q12,
    output logic [149:0] pair_peak_codes,
    output logic [383:0] pair_margin_q15,
    output logic [41:0] pair_mask_counts,
    output logic [65:0] ifft_input_counts, ifft_output_counts,
    output logic [47:0] ifft_status_records,
    output logic [5:0] ifft_status_seen,
    output logic signed [22:0] ux_q20, uy_q20,
    output logic [63:0] residual_square_q24, norm_square_q40,
    output logic [7:0] direction_reason,
    output logic [7:0] first_error_code,
    output logic transaction_cancelled,
    output logic abort_valid, input logic abort_ready,
    output logic [7:0] first_cancel_causes, accumulated_cancel_causes,
    output logic [23:0] abort_pair_state,
    output logic [83:0] abort_stage_state,
    output logic [5:0] abort_hardware_started, abort_physically_retired,
    output logic [65:0] abort_ifft_input_counts, abort_ifft_output_counts,
    output logic [5:0] abort_ifft_status_seen,
    output logic [3:0] abort_ip_transfers,
    output logic busy, ip_obligation,
    output logic [4:0] debug_state
);
  logic reserve_valid,reserve_ready;
  logic [724:0] reserve_identity;
  always_comb begin
    reserve_valid=!busy && (s_valid || s_terminal_valid || s_abort_valid);
    if(s_valid) reserve_identity={s_token,s_generation,s_context,s_frame_first};
    else if(s_terminal_valid) reserve_identity=s_terminal_data[6625:5901];
    else reserve_identity=s_abort_identity;
  end
  pcm4_doa_backend backend (
    .clk(clk),
    .cold_rst_n(cold_rst_n),
    .begin_valid(reserve_valid),
    .begin_ready(reserve_ready),
    .begin_token(reserve_identity[724:661]),
    .begin_generation(reserve_identity[660:597]),
    .begin_context(reserve_identity[596:432]),
    .begin_frame_first(reserve_identity[431:0]),
    .gate_evidence_valid(gate_evidence_valid && gate_identity==reserve_identity),
    .gate_qualified(gate_qualified),
    .gate_policy_id(gate_policy_id),
    .s_valid(s_valid),
    .s_ready(s_ready),
    .s_token(s_token),
    .s_generation(s_generation),
    .s_context(s_context),
    .s_frame_first(s_frame_first),
    .s_domain(s_domain),
    .s_channel(s_channel),
    .s_bin(s_bin),
    .s_real(s_real),
    .s_imag(s_imag),
    .s_numeric_valid(s_numeric_valid),
    .s_ov_real(s_ov_real),
    .s_ov_imag(s_ov_imag),
    .s_qualified(s_qualified),
    .s_terminal_valid(s_terminal_valid),
    .s_terminal_ready(s_terminal_ready),
    .s_terminal_data(s_terminal_data),
    .s_abort_valid(s_abort_valid),
    .s_abort_ready(s_abort_ready),
    .s_abort_identity(s_abort_identity),
    .s_abort_data(s_abort_data),
    .cancel_now(cancel_now),
    .stop_now(stop_now),
    .cancel_causes(cancel_causes),
    .cancel_identity(cancel_identity),
    .frontend_cancel_request(frontend_cancel_request),
    .active_identity(active_identity),
    .ip_config_data(ip_config_data),
    .ip_config_valid(ip_config_valid),
    .ip_config_ready(ip_config_ready),
    .ip_input_data(ip_input_data),
    .ip_input_valid(ip_input_valid),
    .ip_input_last(ip_input_last),
    .ip_input_ready(ip_input_ready),
    .ip_output_data(ip_output_data),
    .ip_output_index(ip_output_index),
    .ip_output_valid(ip_output_valid),
    .ip_output_last(ip_output_last),
    .ip_output_ready(ip_output_ready),
    .ip_status_data(ip_status_data),
    .ip_status_valid(ip_status_valid),
    .ip_status_ready(ip_status_ready),
    .ip_event_unexpected_last(ip_event_unexpected_last),
    .ip_event_missing_last(ip_event_missing_last),
    .ip_event_overflow(ip_event_overflow),
    .report_valid(report_valid),
    .report_ready(report_ready),
    .angle_q8(angle_q8),
    .angle_numerical_valid(angle_numerical_valid),
    .angle_delivery_eligible(angle_delivery_eligible),
    .report_gate_evidence_valid(report_gate_evidence_valid),
    .report_gate_qualified(report_gate_qualified),
    .report_gate_policy_id(report_gate_policy_id),
    .frontend_terminal_record(frontend_terminal_record),
    .frontend_abort_seen(frontend_abort_seen),
    .frontend_abort_identity_record(frontend_abort_identity_record),
    .frontend_abort_record(frontend_abort_record),
    .pair_state(pair_state),
    .backend_stage_state(backend_stage_state),
    .pair_hardware_started(pair_hardware_started),
    .pair_physically_retired(pair_physically_retired),
    .pair_valid(pair_valid),
    .pair_tau_q12(pair_tau_q12),
    .pair_peak_codes(pair_peak_codes),
    .pair_margin_q15(pair_margin_q15),
    .pair_mask_counts(pair_mask_counts),
    .ifft_input_counts(ifft_input_counts),
    .ifft_output_counts(ifft_output_counts),
    .ifft_status_records(ifft_status_records),
    .ifft_status_seen(ifft_status_seen),
    .ux_q20(ux_q20),
    .uy_q20(uy_q20),
    .residual_square_q24(residual_square_q24),
    .norm_square_q40(norm_square_q40),
    .direction_reason(direction_reason),
    .first_error_code(first_error_code),
    .transaction_cancelled(transaction_cancelled),
    .abort_valid(abort_valid),
    .abort_ready(abort_ready),
    .first_cancel_causes(first_cancel_causes),
    .accumulated_cancel_causes(accumulated_cancel_causes),
    .abort_pair_state(abort_pair_state),
    .abort_stage_state(abort_stage_state),
    .abort_hardware_started(abort_hardware_started),
    .abort_physically_retired(abort_physically_retired),
    .abort_ifft_input_counts(abort_ifft_input_counts),
    .abort_ifft_output_counts(abort_ifft_output_counts),
    .abort_ifft_status_seen(abort_ifft_status_seen),
    .abort_ip_transfers(abort_ip_transfers),
    .busy(busy),
    .ip_obligation(ip_obligation),
    .debug_state(debug_state)
  );
endmodule
