"""Render diagnosis tables from audited saved data."""
import study as d

def render():
    a=d.s.read(d.HERE/'analysis.json');ss=a['summaries'];ix={(r['condition'],r['intervention'],r['beta']):r for r in ss}
    conditions=sorted({r['condition'] for r in ss})
    lines=['# 单频噪声＋允许范围边缘：退步原因','',
        '结论：β=.75保留幅度权重，使强1kHz成分在GCC中的相对权重上升，麦对时延偏离直达几何更多；28°方向仅距30°锥边界2°，小偏差更容易越界并失去输出。原场景主要损失出在候选出锥，而非5/12等待不足。混响本身也有边缘效应，不能把全部退步归因于单频干扰。',
        '', '## 证据链', '',
        '1. 同一帧的频点掩码在两个β下完全相同；改变的是保留频点的权重。PHAT将每个保留频点的幅度归一为1，β=.75留下 |互谱|^0.25。1kHz附近900–1100Hz的平均权重占比在原单频条件约从9%–11%升到14%–18%。这是归一权重幅度之和，不是能量占比。',
        '2. 9个原单频条件的麦对时延RMSE均上升。例如仰角边缘+直达从0.116升至0.208样点；+早反射从0.289升至0.330样点。RMSE以直达路径几何为参考，反射声场不存在唯一的混合声到达真值；只统计有限时延，不能脱离拒绝率解读。',
        '3. 6个边缘条件汇总每方法4800个稳定有目标帧：正确输出3786→3598，净少188；基线拒绝22→44（+22），有效候选出锥942→1100（+158），锥内等待/跳变50→58（+8）。四类互斥且覆盖全部帧；本组新鲜输出均在10°误差内。因此净损失约84.0%对应出锥增加。该分解是同帧结果归类，不把每一帧的中介因果当作已证明。',
        '4. 保持候选、种子和其他跟踪规则不变，仅将允许锥半角改为40°作诊断，两算法正确输出差距188→23帧，缩小87.8%。此对照验证门限的放大作用，不代表允许更宽范围安全；未测试范围外干扰，不应部署40°。',
        '5. 移除正弦而保留原白噪声比例后，三个直达方向的β差距均归零；方位边缘+早反射从−5.81变为+0.12个百分点。但仰角边缘+早反射仍为−1.63，+尾声仍为−1.34，说明反射与边界仍有独立残余效应。',
        '6. 等整段总RMS宽带替换后，9个条件的β=.75正确率差值均转正。不能据此说宽带噪声更容易：其绝对正确率普遍更低。该对照只说明方法间优劣依赖干扰频谱分布，而不是只取决于全频噪声功率。',
        '', '## 全部条件及干预结果', '',
        '正确率=误差≤10°的新鲜跟踪输出/全部稳定有目标帧；以下差值均为新β=.75减原PHAT，单位百分点。每条件3种子，同一干预内两算法输入完全相同。',
        '', '| 条件 | 原单频正确率 原→新/% | 原单频差值 | 移除单频后差值 | 等RMS宽带替换差值 | 40°诊断差值（原单频） |',
        '|---|---:|---:|---:|---:|---:|']
    for c in conditions:
        def pair(v):return ix[c,v,'1'],ix[c,v,'0.75']
        old,new=pair('original_tone')
        def delta(v):
            x,y=pair(v);return 100*(y['correct']-x['correct'])/x['frames']
        lines.append(f"| {c} | {100*old['correct']/old['frames']:.2f}→{100*new['correct']/new['frames']:.2f} | {delta('original_tone'):+.2f} | {delta('tone_removed'):+.2f} | {delta('equal_rms_band'):+.2f} | {100*(new['wide_correct']-old['wide_correct'])/old['frames']:+.2f} |")
    lines+=['', '## 原单频：候选质量及门限分解', '',
        '| 条件 | 帧数 | 拒绝 原→新 | 出锥 原→新 | 锥内等待 原→新 | 麦对RMSE 原→新/样点 | 1kHz附近权重 原→新/% |',
        '|---|---:|---:|---:|---:|---:|---:|']
    for c in conditions:
        x,y=ix[c,'original_tone','1'],ix[c,'original_tone','0.75']
        lines.append(f"| {c} | {x['frames']} | {x['rejected']}→{y['rejected']} | {x['outside']}→{y['outside']} | {x['waiting']}→{y['waiting']} | {x['pair_rmse_mean']:.3f}→{y['pair_rmse_mean']:.3f} | {100*x['tone_weight_share_mean']:.2f}→{100*y['tone_weight_share_mean']:.2f} |")
    lines+=['', '## 配对损失与种子差异', '',
        '净损失计数可被两方向转换抵消。以下列出旧方法正确而新方法失去正确输出的帧，和反向挽回的帧；逐帧分类见analysis.json的flows。',
        '', '| 条件 | 丢失正确帧 | 挽回正确帧 | 丢失中出锥 | 三种子正确率差值范围/百分点 |', '|---|---:|---:|---:|---:|']
    for c in conditions:
        flow=next(f for f in a['flows'] if f['condition']==c and f['intervention']=='original_tone')
        ds=[]
        for seed in ['2026091200','2026091201','2026091202']:
            x,y=[next(r for r in a['per_seed'] if (r['condition'],r['intervention'],r['seed'],r['beta'])==(c,'original_tone',seed,b)) for b in ['1','0.75']]
            ds.append(100*(y['correct']-x['correct'])/x['frames'])
        lines.append(f"| {c} | {sum(flow['lost'].values())} | {sum(flow['gained'].values())} | {flow['lost'].get('outside_cone',0)} | {min(ds):+.2f}～{max(ds):+.2f} |")
    lines+=['', '## 实验设计与边界', '',
        '81个配对试验：3方向×3传播条件×3历史种子×3干预；每份输入分别跑β=1/.75、30°/40°四个跟踪会话。全程保持六麦布局、原定位验收门限、5/12及时间规则不变。保存43200条稳定有目标候选诊断记录；状态会话仍处理全部467帧，过渡/缺席帧未删掉后拼接。',
        '原单频输入按历史哈希复现；tone_removed使用相同目标、RIR和保留原缩放白噪声，直接移除正弦，不重新归一到1；equal_rms_band使用独立随机流[seed,300+麦号]生成同频带探测噪声，加白噪声后归一到原总RMS。等RMS不保证相同带内SNR，控制的是整段每通道总功率。',
        '无新保护机制，无参数选择。特意复用2026091200–1202以回溯已批准结果；这是解释性干预实验，不是新的独立验证集，不宣称统计显著性或实场适用。三种子结果有差异，不能假设每种环境或每个种子都退步。',
        '标注在定位和会话更新后添加，未用于算法选择。原单频帧与冻结本地证据的28800条原始/跟踪记录逐项核对通过；不宣称与A侧文件逐字节相同。A此前已记录浮点差异。',
        '', '## 下一步应做什么', '',
        '优先研究候选层的窄带集中度诊断与保护，而非再放宽捕获条件。可以在另设开发集对比限制强频点权重或可解释的PHAT回退；需要先验证诊断量能区分“窄带污染”与正常目标窄带成分，不能把集中度高直接等同于干扰。',
        '同时保留30°正式允许范围，记录边界距离与候选不确定性。保护机制冻结后再用全新种子、更多单频频率、边界内外方向和混响验证，重点防止把允许范围外声源引入。当前不实现或推荐扩大锥角，也不根据已看过的这一批重新宣布验证通过。',
        '', '## 交付与复核', '',
        '本轮源文件、协议、测试、结果和说明集中在research/tonal-edge-01。原已批准496个文件全部保持哈希不变；当前成果是新的待复核增量，不继承A对前轮的批准。默认算法未改，未覆盖/合并总工程，未提交或推送。',
        '指定复核人：拓芙（A）。A应复核控制变量、频谱权重计算、净损失分解与40°反事实限制。确认准确版本后由A决定合入。']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    p=d.HERE/'REPORT.md'
    if p.exists():raise ValueError('output exists')
    p.write_text(render(),encoding='utf-8')
